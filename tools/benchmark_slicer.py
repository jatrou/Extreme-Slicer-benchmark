#!/usr/bin/env python3
"""Run repeatable CPU/CUDA Orca CLI slices without buffering large logs.

The Windows console shim must sit beside OrcaSlicer.dll and resources. Run
``python tools/benchmark_slicer.py --help`` for fixture and run options.
All generated data is written outside the source checkout by default.
"""

import argparse
import ctypes
import hashlib
import json
import math
import os
from pathlib import Path
import re
import shutil
import statistics
import struct
import subprocess
import sys
import threading
import time
import zipfile


RESULT_PREFIX = "ORCA_BENCH_RESULT "
VOLATILE_COMMENT = re.compile(
    rb"^\s*;\s*(?:generated\s+(?:at|on)|date|timestamp|time\s*stamp)\s*[:=]",
    re.IGNORECASE,
)
HEADER_TIMESTAMP = re.compile(
    rb"^(; generated by .+ on )\d{4}-\d{2}-\d{2} at \d{2}:\d{2}:\d{2}(\r?\n)?$"
)
OBJECT_COMMENT_ID = re.compile(
    rb"^(; (?:stop )?printing object .+ id:)\d+( copy \d+\r?\n)$"
)
GCODE_SUFFIXES = (".gcode", ".gco", ".gc")


def make_fixture(path, segments=960, rings=64):
    """Write a closed corrugated cylinder as binary STL, deterministically."""
    if segments < 32 or rings < 2:
        raise ValueError("fixture needs at least 32 segments and 2 rings")
    path.parent.mkdir(parents=True, exist_ok=True)
    def vertex(i, j):
        angle = math.tau * (i % segments) / segments
        z = 20.0 * j / rings
        radius = 43.0 + 1.7 * math.sin(23.0 * angle + 0.23 * j) + 0.5 * math.sin(47.0 * angle)
        return (radius * math.cos(angle), radius * math.sin(angle), z)

    triangle_count = 2 * segments * rings + 2 * segments
    with path.open("wb") as out:
        out.write(b"Orca benchmark corrugated cylinder".ljust(80, b"\0"))
        out.write(struct.pack("<I", triangle_count))
        def tri(a, b, c):
            # STL readers can calculate normals from the winding.
            out.write(struct.pack("<12fH", 0.0, 0.0, 0.0, *a, *b, *c, 0))
        for j in range(rings):
            for i in range(segments):
                a, b = vertex(i, j), vertex(i + 1, j)
                c, d = vertex(i, j + 1), vertex(i + 1, j + 1)
                tri(a, b, d)
                tri(a, d, c)
        for i in range(segments):
            tri((0.0, 0.0, 0.0), vertex(i + 1, 0), vertex(i, 0))
            tri((0.0, 0.0, 20.0), vertex(i, rings), vertex(i + 1, rings))
    return triangle_count


def resolved_profile(directory, name, seen=None):
    """Expand the bundled BBL preset chain before passing JSON to the CLI."""
    seen = set() if seen is None else seen
    if name in seen:
        raise ValueError(f"cyclic preset inheritance: {name}")
    seen.add(name)
    path = directory / (name + ".json")
    data = json.loads(path.read_text(encoding="utf-8"))
    parent = data.get("inherits")
    merged = resolved_profile(directory, parent, seen) if parent else {}
    merged.update(data)
    seen.remove(name)
    return merged


def fixture_profiles(repo_resources, folder):
    """Create fully resolved, fixed X1C settings for the STL."""
    base = repo_resources / "profiles" / "BBL"
    definitions = [
        ("machine", "Bambu Lab X1 Carbon 0.4 nozzle", "machine.json"),
        ("process", "0.20mm Standard @BBL X1C", "process.json"),
        ("filament", "Bambu PLA Basic @BBL X1C", "filament.json"),
    ]
    folder.mkdir(parents=True, exist_ok=True)
    paths = {}
    for kind, name, filename in definitions:
        data = resolved_profile(base / kind, name)
        data.pop("inherits", None)
        if kind == "process":
            data["sparse_infill_pattern"] = "rectilinear"
            data["internal_solid_infill_pattern"] = "rectilinear"
            data["top_surface_pattern"] = "rectilinear"
            data["bottom_surface_pattern"] = "rectilinear"
            data["sparse_infill_density"] = "100%"
            data["layer_height"] = "0.2"
            data["initial_layer_print_height"] = "0.2"
        path = folder / filename
        path.write_text(json.dumps(data, indent=2), encoding="utf-8")
        paths[kind] = path
    return [paths["machine"], paths["process"]], [paths["filament"]]


def memory_bytes(pid):
    """Peak working set for the benchmark process; unavailable returns None."""
    if os.name == "nt":
        from ctypes import wintypes
        class Counters(ctypes.Structure):
            _fields_ = [("cb", wintypes.DWORD), ("PageFaultCount", wintypes.DWORD),
                       ("PeakWorkingSetSize", ctypes.c_size_t), ("WorkingSetSize", ctypes.c_size_t),
                       ("QuotaPeakPagedPoolUsage", ctypes.c_size_t), ("QuotaPagedPoolUsage", ctypes.c_size_t),
                       ("QuotaPeakNonPagedPoolUsage", ctypes.c_size_t), ("QuotaNonPagedPoolUsage", ctypes.c_size_t),
                       ("PagefileUsage", ctypes.c_size_t), ("PeakPagefileUsage", ctypes.c_size_t)]
        kernel = ctypes.WinDLL("kernel32", use_last_error=True)
        psapi = ctypes.WinDLL("psapi", use_last_error=True)
        kernel.OpenProcess.argtypes = [wintypes.DWORD, wintypes.BOOL, wintypes.DWORD]
        kernel.OpenProcess.restype = wintypes.HANDLE
        psapi.GetProcessMemoryInfo.argtypes = [wintypes.HANDLE, ctypes.POINTER(Counters), wintypes.DWORD]
        psapi.GetProcessMemoryInfo.restype = wintypes.BOOL
        kernel.CloseHandle.argtypes = [wintypes.HANDLE]
        handle = kernel.OpenProcess(0x1000 | 0x0400, False, pid)
        if not handle:
            return None
        try:
            counters = Counters()
            counters.cb = ctypes.sizeof(counters)
            return counters.PeakWorkingSetSize if psapi.GetProcessMemoryInfo(handle, ctypes.byref(counters), counters.cb) else None
        finally:
            kernel.CloseHandle(handle)
    status = Path(f"/proc/{pid}/status")
    if status.exists():
        for line in status.read_text(errors="replace").splitlines():
            if line.startswith("VmHWM:"):
                return int(line.split()[1]) * 1024
    return None


def gpu_sample():
    exe = shutil.which("nvidia-smi")
    if not exe:
        return None
    try:
        result = subprocess.run(
            [exe, "--query-gpu=utilization.gpu,memory.used,power.draw", "--format=csv,noheader,nounits"],
            capture_output=True, text=True, timeout=5, check=True,
            creationflags=subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0,
        )
        values = [float(item.strip()) for item in result.stdout.splitlines()[0].split(",")]
        return dict(zip(("utilization_percent", "memory_mib", "power_w"), values))
    except (OSError, subprocess.SubprocessError, ValueError, IndexError):
        return None


def parse_log(path):
    found = []
    with path.open("rb") as log:
        for line in log:
            pos = line.find(RESULT_PREFIX.encode())
            if pos < 0:
                continue
            try:
                found.append(json.loads(line[pos + len(RESULT_PREFIX):].decode("utf-8", "replace")))
            except json.JSONDecodeError:
                found.append({"parse_error": line[pos:pos + 500].decode("utf-8", "replace")})
    return found


def hash_stream(stream, normalized=False):
    digest = hashlib.sha256()
    for line in stream:
        if normalized:
            header = HEADER_TIMESTAMP.match(line)
            if header:
                digest.update(header.group(1) + b"<timestamp>" + (header.group(2) or b""))
                continue
            if VOLATILE_COMMENT.match(line):
                continue
            # Repeated CPU-only runs also vary this annotation. Preserve the
            # object name, copy index, unique label comments and all commands.
            line = OBJECT_COMMENT_ID.sub(rb"\1<object-id>\2", line)
        digest.update(line)
    return digest.hexdigest()


def hashes(path):
    with path.open("rb") as stream:
        raw = hash_stream(stream)
    with path.open("rb") as stream:
        norm = hash_stream(stream, True)
    return {"sha256": raw, "normalized_sha256": norm, "bytes": path.stat().st_size}


def hash_file(path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def collect_gcode(folder):
    files = {}
    for path in sorted(folder.rglob("*")):
        if not path.is_file():
            continue
        name = path.name.lower()
        relative = str(path.relative_to(folder))
        if name.endswith(GCODE_SUFFIXES):
            files[relative] = hashes(path)
        elif name.endswith(".gcode.3mf"):
            # 3MF container metadata may vary; compare the actual toolpath members.
            try:
                with zipfile.ZipFile(path) as archive:
                    for member in archive.namelist():
                        if member.lower().endswith(GCODE_SUFFIXES):
                            with archive.open(member) as stream:
                                raw = hash_stream(stream)
                            with archive.open(member) as stream:
                                norm = hash_stream(stream, True)
                            files[relative + "!" + member] = {"sha256": raw, "normalized_sha256": norm}
            except zipfile.BadZipFile:
                files[relative] = {"error": "invalid gcode.3mf archive"}
    return files


def classify(returncode, backend, rows, gcode):
    if returncode != 0:
        return "process_failed"
    if any(item.get("error") or not item.get("normalized_sha256") for item in gcode.values()):
        return "invalid_gcode"
    if backend == "stock":
        return "ok" if gcode else "no_gcode"
    if not rows or any("parse_error" in row for row in rows):
        return "missing_or_invalid_benchmark_result"
    if any(row.get("outcome") in ("validation_failed", "cuda_fallback") for row in rows):
        return str(next(row["outcome"] for row in rows if row.get("outcome") in ("validation_failed", "cuda_fallback")))
    if any(int(row.get("validation_failures", 0)) != 0 for row in rows):
        return "validation_failed"
    if backend == "cuda" and not all(
        row.get("active_backend") == "CUDA" and
        row.get("outcome", "cuda_complete") == "cuda_complete" and
        row.get("gpu_performance_valid", True) and
        int(row.get("accepted_gpu_intersections", 0)) > 0
        for row in rows
    ):
        return "no_gpu_acceleration_evidence"
    if not gcode:
        return "no_gcode"
    return "ok"


def run_one(exe, project, folder, backend, strict, batch_size, settings, filaments, sample_gpu, timeout, allow_newer_file, overrides=()):
    folder.mkdir(parents=True, exist_ok=False)
    data_dir = folder / "datadir"
    output_dir = folder / "sliced"
    data_dir.mkdir()
    output_dir.mkdir()
    args = [str(exe), "--datadir", str(data_dir), "--outputdir", str(output_dir),
            "--slice", "1" if project.suffix.lower() == ".3mf" else "0"]
    if allow_newer_file:
        args.append("--allow-newer-file")
    if settings:
        args.extend(("--load-settings", ";".join(str(p) for p in settings)))
    if filaments:
        args.extend(("--load-filaments", ";".join(str(p) for p in filaments)))
        args.append("--load-defaultfila")
    args.extend("--" + key.replace("_", "-") + "=" + value for key, value in overrides)
    args.append(str(project))
    env = os.environ.copy()
    for key in ("ORCA_BENCH_BACKEND", "ORCA_BENCH_STRICT", "ORCA_BENCH_BATCH_SIZE", "ORCA_VULKAN_SLICER_VALIDATION"):
        env.pop(key, None)
    if backend != "stock":
        env.update(ORCA_BENCH_BACKEND=backend, ORCA_BENCH_STRICT=str(int(strict)), ORCA_BENCH_BATCH_SIZE=str(batch_size))
    logfile = folder / "stdout.log"
    start = time.perf_counter()
    peak = None
    gpu_samples = []
    with logfile.open("wb") as output:
        proc = subprocess.Popen(args, cwd=exe.parent, env=env, stdout=output, stderr=subprocess.STDOUT,
                                creationflags=subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0)
        stop_monitor = threading.Event()
        def monitor():
            nonlocal peak
            while not stop_monitor.is_set():
                peak_now = memory_bytes(proc.pid)
                if peak_now is not None:
                    peak = max(peak or 0, peak_now)
                if sample_gpu:
                    sample = gpu_sample()
                    if sample:
                        gpu_samples.append(sample)
                stop_monitor.wait(1)
        monitor_thread = threading.Thread(target=monitor, daemon=True)
        monitor_thread.start()
        timed_out = False
        try:
            proc.wait(timeout=timeout if timeout else None)
        except subprocess.TimeoutExpired:
            timed_out = True
            proc.kill()
            proc.wait()
        except KeyboardInterrupt:
            proc.kill()
            proc.wait()
            raise
        finally:
            # Set the wall clock immediately after process completion, before
            # waiting for optional GPU sampling to finish.
            elapsed = (time.perf_counter() - start) * 1000
            stop_monitor.set()
            monitor_thread.join(timeout=5.5 if sample_gpu else 0.2)
    rows = parse_log(logfile)
    gcode = collect_gcode(output_dir)
    result_json = output_dir / "result.json"
    try:
        slicer_result = json.loads(result_json.read_text(encoding="utf-8")) if result_json.exists() else None
    except (UnicodeError, json.JSONDecodeError):
        slicer_result = {"parse_error": "invalid result.json"}
    state = "timeout" if timed_out else classify(proc.returncode, backend, rows, gcode)
    return {
        "backend": backend, "strict": bool(strict) if backend != "stock" else None,
        "batch_size": batch_size if backend != "stock" else None,
        "status": state, "exit_code": proc.returncode, "total_wall_ms": elapsed,
        "peak_working_set_bytes": peak, "gpu_samples": gpu_samples,
        "benchmark_results": rows, "slicer_result": slicer_result,
        "gcode": gcode, "log": str(logfile), "output_dir": str(output_dir),
        "command": args,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--exe", type=Path, help="patched Orca console shim beside OrcaSlicer.dll")
    parser.add_argument("--stock-exe", type=Path, help="optional unpatched Bambu console shim")
    parser.add_argument("--backends", nargs="+", choices=("cpu", "cuda", "stock"),
                        help="backends to run; default CPU and CUDA, plus stock if --stock-exe is given")
    parser.add_argument("--project", type=Path, help="existing .3mf or .stl; omit to generate the controlled STL")
    parser.add_argument("--fixture-only", action="store_true", help="generate STL and exit")
    parser.add_argument("--fixture-segments", type=int, default=960)
    parser.add_argument("--fixture-rings", type=int, default=64)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[2] / "benchmark-runs")
    parser.add_argument("--repo-resources", type=Path, default=Path(__file__).resolve().parents[1] / "resources",
                        help="bundled slicer resources used to resolve STL fixture presets")
    parser.add_argument("--settings", type=Path, action="append", default=[], help="machine/process JSON, repeat for STL")
    parser.add_argument("--filament", type=Path, action="append", default=[], help="filament JSON, repeat for STL")
    parser.add_argument("--runs", type=int, default=1, help="measured runs per backend; repeat after a successful first pass")
    parser.add_argument("--warmups", type=int, default=0, help="unmeasured runs per backend")
    parser.add_argument("--batch-size", type=int, default=64, help="16..4096")
    parser.add_argument("--strict", action="store_true", help="strict CUDA validation; exclude these timings from throughput comparison")
    parser.add_argument("--sample-gpu", action="store_true", help="sample nvidia-smi roughly once per second")
    parser.add_argument("--timeout", type=int, default=0, help="seconds per run; zero means unlimited")
    parser.add_argument("--allow-newer-file", action="store_true", help="allow import of projects from a newer slicer version")
    parser.add_argument("--set", dest="setting_overrides", action="append", default=[], metavar="KEY=VALUE",
                        help="explicit slicer setting override, recorded in the manifest; repeat as needed")
    args = parser.parse_args()
    overrides = []
    for item in args.setting_overrides:
        key, separator, value = item.partition("=")
        if not separator or not re.fullmatch(r"[a-z][a-z0-9_-]*", key) or not value:
            parser.error("--set requires KEY=VALUE with a valid slicer option name")
        overrides.append((key, value))
    if not 16 <= args.batch_size <= 4096 or args.runs < 1 or args.warmups < 0 or args.timeout < 0:
        parser.error("batch size must be 16..4096, runs >= 1, warmups >= 0, timeout >= 0")
    for path in [args.exe, args.stock_exe, args.project, *args.settings, *args.filament]:
        if path is not None and not path.is_file():
            parser.error(f"file not found: {path}")
    selected_backends = args.backends or (["cpu", "cuda"] + (["stock"] if args.stock_exe else []))
    if not args.fixture_only and args.exe is None and any(backend != "stock" for backend in selected_backends):
        parser.error("--exe is required for CPU or CUDA runs")
    if len(set(selected_backends)) != len(selected_backends):
        parser.error("--backends cannot contain duplicates")
    if "stock" in selected_backends and args.stock_exe is None:
        parser.error("--stock-exe is required when stock is selected")
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    run_root = None if args.fixture_only else output / (time.strftime("%Y%m%d-%H%M%S") + "-" + str(os.getpid()))
    if run_root is not None:
        run_root.mkdir()
    fixture_dir = run_root if run_root is not None else output
    project = args.project.resolve() if args.project else fixture_dir / "corrugated-cylinder.stl"
    if args.project is None:
        triangles = make_fixture(project, args.fixture_segments, args.fixture_rings)
        print(f"Fixture: {project} ({triangles} triangles)", flush=True)
    settings = args.settings
    filaments = args.filament
    if project.suffix.lower() == ".stl" and not settings and not filaments:
        try:
            settings, filaments = fixture_profiles(args.repo_resources.resolve(), fixture_dir / "fixture-config")
        except (OSError, ValueError, json.JSONDecodeError) as exc:
            parser.error(f"could not resolve fixture profiles: {exc}")
        print(f"Fixture profiles: {fixture_dir / 'fixture-config'}", flush=True)
    if args.fixture_only:
        return 0
    if project.suffix.lower() not in (".3mf", ".stl"):
        parser.error("project must end in .3mf or .stl")
    executables = [(backend, (args.stock_exe if backend == "stock" else args.exe).resolve())
                   for backend in selected_backends]
    def executable_record(exe, backend):
        library = exe.parent / ("BambuStudio.dll" if backend == "stock" else "OrcaSlicer.dll")
        if not library.is_file():
            parser.error(f"console shim must sit beside {library.name}: {exe}")
        return {"path": str(exe), "sha256": hash_file(exe),
                "slicer_dll": str(library), "slicer_dll_sha256": hash_file(library)}
    manifest = {
        "project": str(project), "project_sha256": hash_file(project),
        "executables": {backend: executable_record(exe, backend) for backend, exe in executables},
        "settings": [str(p.resolve()) for p in settings],
        "settings_sha256": {str(p.resolve()): hash_file(p) for p in settings},
        "filaments": [str(p.resolve()) for p in filaments],
        "filaments_sha256": {str(p.resolve()): hash_file(p) for p in filaments},
        "allow_newer_file": args.allow_newer_file,
        "setting_overrides": dict(overrides),
        "runs": [],
    }
    manifest_path = run_root / "manifest.json"
    try:
        failed_stock = False
        for index in range(args.warmups + args.runs):
            for backend, exe in executables:
                if backend == "stock" and failed_stock:
                    continue
                kind = "warmup" if index < args.warmups else "measure"
                label = f"{backend}-{kind}-{index + 1 if kind == 'warmup' else index - args.warmups + 1}"
                print(f"Running {label}...", flush=True)
                result = run_one(exe, project, run_root / label, backend, args.strict, args.batch_size,
                                 settings, filaments, args.sample_gpu, args.timeout, args.allow_newer_file, overrides)
                result["kind"] = kind
                manifest["runs"].append(result)
                manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
                print(f"  {result['status']}: {result['total_wall_ms'] / 1000:.2f}s", flush=True)
                if result["status"] != "ok":
                    if backend != "stock":
                        print(f"Stopped. Inspect {result['log']}", file=sys.stderr)
                        return 2
                    print(f"Stock run failed; inspect {result['log']}", file=sys.stderr)
                    failed_stock = True
    except KeyboardInterrupt:
        print(f"Interrupted. Partial results: {manifest_path}", file=sys.stderr)
        return 130
    measured = [run for run in manifest["runs"] if run["kind"] == "measure"]
    patched = [run for run in measured if run["backend"] in ("cpu", "cuda") and run["status"] == "ok"]
    if {run["backend"] for run in patched} == {"cpu", "cuda"}:
        reference = patched[0]["gcode"]
        manifest["cpu_cuda_toolpath_hashes_match"] = all(
            {name: data.get("normalized_sha256") for name, data in run["gcode"].items()} ==
            {name: data.get("normalized_sha256") for name, data in reference.items()}
            for run in patched
        )
    else:
        manifest["cpu_cuda_toolpath_hashes_match"] = None
    manifest["summary"] = {}
    for backend, _ in executables:
        group = [run for run in measured if run["backend"] == backend and run["status"] == "ok"]
        if not group:
            manifest["summary"][backend] = {"status": "no_completed_measured_run"}
            continue
        summary = {"total_wall_ms_median": statistics.median(run["total_wall_ms"] for run in group)}
        process_times = [sum(float(row["process_wall_ms"]) for row in run["benchmark_results"])
                         for run in group if run["benchmark_results"]]
        if process_times:
            summary["process_wall_ms_median"] = statistics.median(process_times)
        manifest["summary"][backend] = summary
    cpu = manifest["summary"].get("cpu", {}).get("process_wall_ms_median")
    cuda = manifest["summary"].get("cuda", {}).get("process_wall_ms_median")
    if cpu and cuda and not args.strict and manifest["cpu_cuda_toolpath_hashes_match"] is True:
        manifest["summary"]["cpu_cuda_process_speedup"] = cpu / cuda
    if args.strict:
        manifest["summary"]["note"] = "Strict validation adds CPU work; process time is not a throughput comparison."
    manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(f"Results: {manifest_path}")
    print(f"CPU/CUDA normalized G-code hashes match: {manifest['cpu_cuda_toolpath_hashes_match']}")
    if failed_stock:
        return 2
    return 3 if manifest["cpu_cuda_toolpath_hashes_match"] is False else 0


if __name__ == "__main__":
    sys.exit(main())
